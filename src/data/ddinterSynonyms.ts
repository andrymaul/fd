/**
 * Returns all canonical and alternative names for a given drug
 * to ensure maximum recall against DDInter 2.0 databases.
 */
export function getDDInterCanonicalNames(drugName: string): string[] {
  if (!drugName) return [];
  const clean = drugName.toLowerCase().trim();
  const names = new Set<string>();

  // 1. Direct name
  names.add(clean);

  // 2. Name without parenthetical qualifiers e.g. "Paracetamol (oral)" -> "Paracetamol"
  const withoutParen = clean.replace(/\s*\([^)]*\)/g, '').trim();
  if (withoutParen) names.add(withoutParen);

  // 3. Name without dosage/salt e.g. "Metformin HCl 500 mg" -> "Metformin"
  const stripped = withoutParen
    .replace(/\b(hcl|hydrochloride|sodium|potassium|maleate|succinate|tartrate|sulfate|phosphate|besylate|mesylate|fumarate|calcium)\b/gi, '')
    .replace(/\b\d+(\.\d+)?\s*(mg|g|mcg|ml|iu|%)\b/gi, '')
    .trim();
  if (stripped) names.add(stripped);

  // 4. Exact match in DDINTER_SYNONYM_MAP
  [clean, withoutParen, stripped].forEach(key => {
    if (DDINTER_SYNONYM_MAP[key]) {
      DDINTER_SYNONYM_MAP[key].forEach(syn => names.add(syn.toLowerCase().trim()));
    }
  });

  // 5. Morphological standardizations
  const currentList = Array.from(names);
  currentList.forEach(name => {
    if (name.endsWith('in') && !name.endsWith('oin') && !name.endsWith('sin')) names.add(name + 'e');
    if (name.endsWith('ine')) names.add(name.slice(0, -1));
    if (name.endsWith('id')) names.add(name + 'e');
    if (name.endsWith('ide')) names.add(name.slice(0, -1));
    if (name.endsWith('at')) names.add(name.slice(0, -1) + 'te');
    if (name.endsWith('ate')) names.add(name.slice(0, -2) + 't');
  });

  return Array.from(names);
}
